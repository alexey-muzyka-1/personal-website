-- Ответ на единственный вопрос бота: человек ведёт контент сам или с
-- командой. Хранится у пользователя, а не только в событии: по нему
-- выбирать, кому что предлагать, когда появится что продавать.
--
-- Пустая строка вместо NULL — значит «не спрашивали». NULL в group by
-- молча съедает строки и врёт в отчётах.
alter table users add column if not exists role text not null default '';

-- Разрез «сколько одиночек, сколько команд» будет самым частым.
create index if not exists users_role_idx on users (role) where role <> '';
