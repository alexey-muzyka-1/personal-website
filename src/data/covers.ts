// Обложки, которых не было.
//
// У статей картинки уже есть — сделаны руками, с цифрами результата
// (`/metod-6x5/og.png` и соседние). Они лучше того, что даёт генератор:
// в чате продают именно цифры. Поэтому здесь их нет и заменять их нечем.
//
// Сюда попадает то, у чего картинки не существует. Сейчас это канал.
// Когда появится статья без своей обложки — добавить строку, и она
// соберётся из тех же данных той же вёрсткой.
//
// Даты в обложке нет намеренно. На странице она уместна: там видно всю
// статью. В чате картинка живёт отдельно от контекста и переживает свой
// месяц — «14 августа 2026» через полгода читается как несвежий товар.

export interface Cover {
  slug: string;
  /** kicker — рубрика над заголовком, как на странице статьи. */
  kicker: string;
  title: string;
  subtitle: string;
  /** foot — что стоит в нижней строке справа: адрес или @имя. */
  foot: string;
}

